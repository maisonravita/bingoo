/** Centre d'une liste de départements (Paris par défaut si la zone est vide ou inconnue). */
export function centerOf(zone = []) {
  const pts = zone.map((d) => DEPTS[d]).filter(Boolean);
  if (!pts.length) return [46.6, 2.4];
  return [pts.reduce((s, p) => s + p[0], 0) / pts.length, pts.reduce((s, p) => s + p[1], 0) / pts.length];
}

/** Position en km (est, nord) d'un point par rapport au centre. */
export function offsetKm([lat0, lon0], [lat, lon]) {
  return [(lon - lon0) * 111.32 * Math.cos((lat0 * Math.PI) / 180), (lat - lat0) * 110.57];
}
